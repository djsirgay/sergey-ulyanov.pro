const originals = new WeakMap();
const attributes = new WeakMap();
const page = document.body.dataset.wayfindingPage;
const enTitle = document.title;
const language = () => document.documentElement.lang.toLowerCase().startsWith('be') ? 'be' : 'en';

// Navigation can mount before this page module. Set the root language once from the
// explicit URL, then saved preference, then markup; its observer will update the shell.
function initialLanguage() {
  const query = new URL(location.href).searchParams.get('lang');
  if (query === 'en' || query === 'be') return query;
  try {
    const saved = localStorage.getItem('research-lang');
    if (saved === 'en' || saved === 'be') return saved;
  } catch { /* Private or blocked storage must not prevent rendering. */ }
  return language();
}
document.documentElement.lang = initialLanguage();

function translate() {
  const isBe = language() === 'be';
  document.querySelectorAll('[data-wayfinding]').forEach(node => {
    if (!originals.has(node)) originals.set(node, node.textContent);
    node.textContent = isBe ? be[node.dataset.wayfinding] || originals.get(node) : originals.get(node);
  });
  document.querySelectorAll('[data-wayfinding-aria]').forEach(node => {
    if (!attributes.has(node)) attributes.set(node, node.getAttribute('aria-label'));
    node.setAttribute('aria-label', isBe ? be[node.dataset.wayfindingAria] || attributes.get(node) : attributes.get(node));
  });
  document.title = isBe ? `${page === 'tools' ? be.toolsTitle : be.helpTitle} — Unmute Belarus` : enTitle;
  // Preserve the selected language on task routes without changing their fragment or other state.
  document.querySelectorAll('main a[href]').forEach(link => {
    const raw = link.getAttribute('href');
    if (!raw || raw.startsWith('#')) return;
    const url = new URL(raw, location.href);
    if (url.origin !== location.origin || !/^\/(?:research\/|tools\/|help\/|atlas\/|protocol\/|system\/)/.test(url.pathname)) return;
    if (location.hostname === 'research.sergey-ulyanov.pro') url.pathname = url.pathname.replace(/^\/research(?=\/)/, '');
    url.searchParams.set('lang', language());
    link.href = `${url.pathname}${url.search}${url.hash}`;
  });
}

translate();
new MutationObserver(translate).observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
// The shared shell dispatches this event immediately before applying lang + URL.
// Wait until that synchronous change finishes instead of repainting the old language.
const afterShellLanguage = () => queueMicrotask(translate);
window.addEventListener('research:language', afterShellLanguage);
document.addEventListener('research:language', afterShellLanguage);
